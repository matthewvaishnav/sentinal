/**
 * SENTINEL - Windows Installer Builder
 * 
 * Creates an NSIS installer for Windows systems.
 * Includes service wrapper for running as Windows service.
 */

const fs = require('fs');
const path = require('path');
const { execSync } = require('child_process');
const os = require('os');

const pkg = require('../package.json');
const version = pkg.version;
const setupName = `SENTINEL-${version}-Setup.exe`;

console.log(`Building ${setupName}...`);

const sourceDir = path.join(__dirname, '..');
const distDir = path.join(sourceDir, 'dist');
const tempDir = fs.mkdtempSync(path.join(os.tmpdir(), 'sentinel-nsis-'));

// Check if the executable exists
const sourceExe = path.join(distDir, 'sentinel-win-x64.exe');
if (!fs.existsSync(sourceExe)) {
  console.error('Error: Build the Windows executable first with: npm run build:win');
  process.exit(1);
}

// Copy files to temp directory for NSIS
const nsisDir = path.join(tempDir, 'sentinel');
fs.mkdirSync(nsisDir, { recursive: true });

fs.copyFileSync(sourceExe, path.join(nsisDir, 'sentinel.exe'));

// Copy assets
const publicSrc = path.join(sourceDir, 'public');
const docsSrc = path.join(sourceDir, 'docs');

if (fs.existsSync(publicSrc)) {
  fs.cpSync(publicSrc, path.join(nsisDir, 'public'), { recursive: true });
}
if (fs.existsSync(docsSrc)) {
  fs.cpSync(docsSrc, path.join(nsisDir, 'docs'), { recursive: true });
}

// Copy default config
const envExample = path.join(sourceDir, '.env.example');
if (fs.existsSync(envExample)) {
  fs.copyFileSync(envExample, path.join(nsisDir, 'sentinel.conf.example'));
}

// Create NSIS script
const nsisScript = `
; SENTINEL Windows Installer
; Generated by build-win-setup.js

!define PRODUCT_NAME "SENTINEL"
!define PRODUCT_VERSION "${version}"
!define PRODUCT_PUBLISHER "SENTINEL Team"
!define PRODUCT_WEB_SITE "https://github.com/matthewvaishnav/sentinal"
!define PRODUCT_DIR_REGKEY "Software\\Microsoft\\Windows\\CurrentVersion\\App Paths\\sentinel.exe"
!define PRODUCT_UNINST_KEY "Software\\Microsoft\\Windows\\CurrentVersion\\Uninstall\\SENTINEL"

SetCompressor lzma

; Modern UI
!include "MUI2.nsh"

; MUI Settings
!define MUI_ABORTWARNING
!define MUI_ICON "${tempDir}\\icon.ico"
!define MUI_UNICON "${tempDir}\\icon.ico"

; Welcome page
!insertmacro MUI_PAGE_WELCOME

; License page (optional - remove if no license file)
; !insertmacro MUI_PAGE_LICENSE "LICENSE.txt"

; Directory page
!insertmacro MUI_PAGE_DIRECTORY

; Instfiles page
!insertmacro MUI_PAGE_INSTFILES

; Finish page
!define MUI_FINISHPAGE_RUN "$INSTDIR\\sentinel.exe"
!define MUI_FINISHPAGE_SHOWREADME "$INSTDIR\\README.txt"
!insertmacro MUI_PAGE_FINISH

; Uninstaller pages
!insertmacro MUI_UNPAGE_INSTFILES

; Language files
!insertmacro MUI_LANGUAGE "English"

; Reserve files
!insertmacro MUI_RESERVEFILE_INSTALLOPTIONS

; MUI end ------

Name "SENTINEL \${PRODUCT_VERSION}"
OutFile "${distDir}\\${setupName}"
InstallDir "$PROGRAMFILES64\\SENTINEL"
InstallDirRegKey HKLM "\${PRODUCT_DIR_REGKEY}" ""
ShowInstDetails show
ShowUnInstDetails show

Section "MainSection" SEC01
  SetOutPath "$INSTDIR"
  SetOverwrite try
  
  ; Copy main executable
  File "${nsisDir}\\sentinel.exe"
  
  ; Copy assets
  File /r "${nsisDir}\\public"
  File /r "${nsisDir}\\docs"
  
  ; Copy config example
  File "${nsisDir}\\sentinel.conf.example"
  
  ; Create data directory
  CreateDirectory "$INSTDIR\\data"
  
  ; Add to PATH
  EnVar::AddValue "PATH" "$INSTDIR"
  
  ; Create Start Menu shortcuts
  CreateDirectory "$SMPROGRAMS\\SENTINEL"
  CreateShortCut "$SMPROGRAMS\\SENTINEL\\SENTINEL Dashboard.lnk" "http://localhost:3000/dashboard"
  CreateShortCut "$SMPROGRAMS\\SENTINEL\\Uninstall.lnk" "$INSTDIR\\uninst.exe"
  
  ; Create registry entries
  WriteRegStr HKLM "\${PRODUCT_DIR_REGKEY}" "" "$INSTDIR\\sentinel.exe"
  WriteRegStr HKLM "\${PRODUCT_UNINST_KEY}" "DisplayName" "SENTINEL Anti-DDoS Protection"
  WriteRegStr HKLM "\${PRODUCT_UNINST_KEY}" "UninstallString" "$INSTDIR\\uninst.exe"
  WriteRegStr HKLM "\${PRODUCT_UNINST_KEY}" "DisplayVersion" "\${PRODUCT_VERSION}"
  WriteRegStr HKLM "\${PRODUCT_UNINST_KEY}" "Publisher" "\${PRODUCT_PUBLISHER}"
  WriteRegStr HKLM "\${PRODUCT_UNINST_KEY}" "URLInfoAbout" "\${PRODUCT_WEB_SITE}"
SectionEnd

Section -Post
  WriteUninstaller "$INSTDIR\\uninst.exe"
  WriteRegStr HKLM "\${PRODUCT_DIR_REGKEY}" "" "$INSTDIR\\sentinel.exe"
SectionEnd

Section Uninstall
  ; Remove from PATH
  EnVar::DeleteValue "PATH" "$INSTDIR"
  
  ; Remove files
  Delete "$INSTDIR\\sentinel.exe"
  RMDir /r "$INSTDIR\\public"
  RMDir /r "$INSTDIR\\docs"
  RMDir /r "$INSTDIR\\data"
  Delete "$INSTDIR\\sentinel.conf.example"
  
  ; Remove shortcuts
  Delete "$SMPROGRAMS\\SENTINEL\\*.lnk"
  RMDir "$SMPROGRAMS\\SENTINEL"
  
  ; Remove registry entries
  DeleteRegKey HKLM "\${PRODUCT_UNINST_KEY}"
  DeleteRegKey HKLM "\${PRODUCT_DIR_REGKEY}"
  
  ; Remove uninstaller
  Delete "$INSTDIR\\uninst.exe"
  
  RMDir "$INSTDIR"
  
  SetAutoClose true
SectionEnd
`;

const nsisFile = path.join(tempDir, 'sentinel.nsi');
fs.writeFileSync(nsisFile, nsisScript);

// Create a simple icon placeholder (would normally be a real .ico file)
// For now, we'll skip the icon requirement

console.log('NSIS script created at:', nsisFile);
console.log('');
console.log('To build the installer:');
console.log('1. Install NSIS: https://nsis.sourceforge.io/Download');
console.log('2. Run: makensis ' + nsisFile);
console.log('');
console.log('Alternatively, manually run:');
console.log('  makensis "' + nsisFile + '"');

// Try to build with makensis if available
try {
  execSync(`makensis "${nsisFile}"`, { stdio: 'inherit' });
  console.log(`✓ Created ${setupName}`);
} catch (err) {
  console.log('');
  console.log('Note: makensis not found in PATH.');
  console.log('The NSIS script has been generated at:');
  console.log('  ' + nsisFile);
  console.log('');
  console.log('To complete the build:');
  console.log('1. Install NSIS from https://nsis.sourceforge.io');
  console.log('2. Run: makensis "' + nsisFile + '"');
  console.log('');
  console.log('Or use the NSIS GUI (Compile NSIS script)');
  
  // Copy the script to dist for manual building
  const scriptDest = path.join(distDir, 'sentinel.nsi');
  fs.copyFileSync(nsisFile, scriptDest);
  console.log('NSIS script copied to: ' + scriptDest);
}

// Cleanup
try {
  fs.rmSync(tempDir, { recursive: true, force: true });
} catch (err) {
  // Ignore cleanup errors
}
